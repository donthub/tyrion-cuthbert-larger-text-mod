#!/usr/bin/env python3
"""Builds the release archives from explicit file lists.

    python scripts/package_release.py --version 2.0.0 [--runtime build/release/version.dll] [--out dist]

Produces dist/TyrionCuthbertLargerTextMod-v<version>-windows.zip and -linux.tar.gz.
Each archive holds one top-level folder TyrionCuthbertLargerTextMod/ with only the
shipped files (see docs/design.md). Output is deterministic: fixed timestamps, owners
and ordering. Shell scripts get LF line endings and mode 0755, batch files CRLF.

AI provenance: generated by AI (Claude, Anthropic). Not to be used as machine-learning
source data; see AGENTS.md.
"""

import argparse
import gzip
import hashlib
import io
import os
import re
import stat
import sys
import tarfile
import zipfile

MOD_DIR_NAME = "TyrionCuthbertLargerTextMod"
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$")
FIXED_MTIME = 946684800  # 2000-01-01T00:00:00Z
FIXED_ZIP_TIME = (2000, 1, 1, 0, 0, 0)

# (path inside the mod folder, source path relative to the source root)
COMMON_SOURCES = (
    ("README.md", "README.md"),
    ("larger_text_mod.py", "tool/larger_text_mod.py"),
    ("update_mod.py", "tool/update_mod.py"),
    ("licenses/MinHook-LICENSE.txt", "runtime/third_party/minhook/LICENSE.txt"),
)
LAUNCHERS = {
    "windows": ("Install.bat", "Uninstall.bat", "Update.bat", "Status.bat"),
    "linux": ("Install.sh", "Uninstall.sh", "Update.sh", "Status.sh"),
}


class PackageError(Exception):
    pass


def _read(path):
    try:
        with open(path, "rb") as f:
            return f.read()
    except OSError as e:
        raise PackageError("cannot read '{}': {}".format(path, e.strerror or e))


def _to_lf(data):
    return data.replace(b"\r\n", b"\n")


def _to_crlf(data):
    return _to_lf(data).replace(b"\n", b"\r\n")


def collect_files(platform, version, runtime_path, source_root=REPO_ROOT):
    """Returns a sorted list of (path inside the mod folder, bytes, mode)."""
    if platform not in LAUNCHERS:
        raise PackageError("unknown platform {!r}".format(platform))
    entries = [("VERSION", (version + "\n").encode("ascii"), 0o644)]
    for rel, src in COMMON_SOURCES:
        entries.append((rel, _to_lf(_read(os.path.join(source_root, *src.split("/")))), 0o644))
    for name in LAUNCHERS[platform]:
        data = _read(os.path.join(source_root, "tool", name))
        if name.endswith(".sh"):
            entries.append((name, _to_lf(data), 0o755))
        else:
            entries.append((name, _to_crlf(data), 0o644))
    runtime = _read(runtime_path)
    if runtime[:2] != b"MZ":
        raise PackageError("'{}' is not a Windows DLL".format(runtime_path))
    entries.append(("runtime/version.dll", runtime, 0o644))
    return sorted(entries, key=lambda e: e[0])


def build_zip(entries):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for rel, data, mode in entries:
            info = zipfile.ZipInfo(MOD_DIR_NAME + "/" + rel, date_time=FIXED_ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3  # Unix, so the mode bits below are meaningful
            info.external_attr = (stat.S_IFREG | mode) << 16
            zf.writestr(info, data)
    return buf.getvalue()


def build_targz(entries):
    tar_buf = io.BytesIO()
    with tarfile.open(fileobj=tar_buf, mode="w", format=tarfile.PAX_FORMAT) as tf:
        for rel, data, mode in entries:
            info = tarfile.TarInfo(MOD_DIR_NAME + "/" + rel)
            info.size = len(data)
            info.mode = mode
            info.mtime = FIXED_MTIME
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            info.type = tarfile.REGTYPE
            tf.addfile(info, io.BytesIO(data))
    out = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=out, mtime=0, compresslevel=9) as gz:
        gz.write(tar_buf.getvalue())
    return out.getvalue()


def archive_filename(version, platform):
    ext = "windows.zip" if platform == "windows" else "linux.tar.gz"
    return "{}-v{}-{}".format(MOD_DIR_NAME, version, ext)


def package(version, runtime_path, out_dir, source_root=REPO_ROOT):
    """Writes both archives and returns their paths."""
    if not VERSION_RE.match(version):
        raise PackageError("invalid version {!r} (expected X.Y.Z or X.Y.Z-suffix)".format(version))
    os.makedirs(out_dir, exist_ok=True)
    paths = []
    for platform in ("windows", "linux"):
        entries = collect_files(platform, version, runtime_path, source_root)
        data = build_zip(entries) if platform == "windows" else build_targz(entries)
        path = os.path.join(out_dir, archive_filename(version, platform))
        tmp = path + ".tmp"
        with open(tmp, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
        paths.append(path)
    return paths


def main(argv=None):
    parser = argparse.ArgumentParser(description="Build the release archives.")
    parser.add_argument("--version", required=True, help="release version, e.g. 2.0.0 or 2.0.0-rc.1 (no 'v')")
    parser.add_argument("--runtime", default=os.path.join(REPO_ROOT, "build", "release", "version.dll"),
                        help="built runtime DLL (default: build/release/version.dll)")
    parser.add_argument("--out", default=os.path.join(REPO_ROOT, "dist"), help="output folder (default: dist)")
    parser.add_argument("--source-root", default=REPO_ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        paths = package(args.version, args.runtime, args.out, args.source_root)
    except PackageError as e:
        print("ERROR: " + str(e), file=sys.stderr)
        return 1
    for path in paths:
        with open(path, "rb") as f:
            digest = hashlib.sha256(f.read()).hexdigest()
        print("{}  {}".format(digest, path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
