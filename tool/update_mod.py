def build_parser():
    parser = ltm._Parser(prog="update_mod.py",
                         description="Update the Tyrion Cuthbert Larger Text Mod to the latest stable release.")
    parser.add_argument("--check", action="store_true",
                        help="download and validate the latest release without changing any files")
    parser.add_argument("--force", action="store_true",
                        help="reinstall the latest release even if it is not newer")
    parser.add_argument("--game-dir", help="game folder (default: parent of the mod folder)")
    return parser


def run(args, platform, http):
    game_dir, mod_dir = ltm.resolve_dirs(args.game_dir, __file__)
    ltm.ensure_game_not_running(platform)
    ltm.check_game_folder(game_dir, mod_dir)
    manifest = ltm.load_manifest(mod_dir)
    current = ltm.read_mod_version(mod_dir)

    print("Checking GitHub for the latest release...")
    raw = http.get(RELEASES_API_URL, MAX_API_BYTES, "release list", accept="application/vnd.github+json")
    try:
        releases = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError):
        raise ModError("Unexpected response from GitHub (the release list is not valid JSON).",
                       hint="Try again later.")
    tag, release = select_latest_release(releases)
    url, size, sha256 = select_asset(release, tag, platform)
    latest = tag[1:]
    current_key = version_key(current)
    up_to_date = current_key is not None and current_key >= version_key(latest)
    print("Installed version: {}. Latest release: {}.".format(current, latest))
    if up_to_date and not args.check and not args.force:
        print("The mod is already up to date. Nothing was changed.")
        return 0

    print("Downloading {} ({} bytes)...".format(archive_name(tag, platform), size))
    data = http.get(url, MAX_ARCHIVE_BYTES, "release archive")
    if len(data) != size:
        raise ModError("The downloaded archive has {} bytes, but the release metadata says {}; "
                       "refusing it.".format(len(data), size), hint="Nothing was changed. Try again later.")
    if sha256 is not None and hashlib.sha256(data).hexdigest() != sha256:
        raise ModError("The downloaded archive does not match the SHA-256 digest in the release metadata; "
                       "refusing it.", hint="Nothing was changed. Try again later.")
    files = read_archive(data, platform)
    archive_version = files["VERSION"].decode("utf-8", "replace").strip()
    if archive_version != latest:
        raise _bad_archive("its VERSION file says {!r} instead of {!r}".format(archive_version, latest))

    if args.check:
        print("Release {} is valid ({} files{}).".format(
            tag, len(files), ", SHA-256 verified" if sha256 else ", no digest in metadata"))
        if up_to_date:
            print("The mod is up to date. No files were changed (check mode).")
        else:
            print("An update is available. Run Update without --check to install it. No files were changed.")
        return 0

    print("Replacing the mod's files...")
    notes, count = apply_update(game_dir, mod_dir, files, manifest, latest)
    print("")
    print("Update complete: {} -> {} ({} file(s) replaced). config.ini and the log were not changed.".format(
        current, latest, count))
    for note in notes:
        print("Note: " + note)
    if manifest is None:
        print("The mod is not installed in the game yet. Run Install to activate it.")
    else:
        print("The new version is active at the next game start; no re-install is needed.")
    if platform == "linux":
        print("")
        for line in ltm.proton_note_lines():
            print(line)
    return 0


def main(argv=None, http=None):
    ltm.setup_stdio()
    parser = build_parser()
    try:
        args = parser.parse_args(argv)
    except ltm.UsageError as e:
        ltm.print_error(str(e), hint="Run with --help for usage.")
        return 2
    except SystemExit as e:  # --help
        return e.code if isinstance(e.code, int) else 0
    try:
        platform = ltm.check_platform()
        return run(args, platform, http or HttpClient())
    except ModError as e:
        ltm.print_error(e.message, e.hint)
        return 1
    except KeyboardInterrupt:
        ltm.print_error("Interrupted.")
        return 130
    except Exception as e:
        ltm.print_error("Unexpected error: {}: {}".format(type(e).__name__, e),
                        hint="Please report this on the mod's GitHub page.")
        return 1


if __name__ == "__main__":
    sys.exit(main())
