# Archive validation (in memory)
# ---------------------------------------------------------------------------

def _bad_archive(detail):
    return ModError("The release archive was rejected: {}.".format(detail),
                    hint="Nothing was changed. Try again later or report this on the mod's GitHub page.")


def _zip_entries(data):
    try:
        zf = zipfile.ZipFile(io.BytesIO(data))
        infos = zf.infolist()
    except (zipfile.BadZipFile, zipfile.LargeZipFile, ValueError, OSError) as e:
        raise _bad_archive("not a valid zip file ({})".format(e))
    if len(infos) > MAX_ARCHIVE_ENTRIES:
        raise _bad_archive("too many entries")
    total = 0
    for info in infos:
        mode = (info.external_attr >> 16) & 0xFFFF
        if stat.S_ISLNK(mode):
            raise _bad_archive("'{}' is a link".format(info.filename))
        if info.flag_bits & 0x1:
            raise _bad_archive("'{}' is encrypted".format(info.filename))
        name = info.orig_filename  # unsanitized, so backslashes are seen on every platform
        if name.endswith("/"):
            yield name[:-1], "dir", None
            continue
        if stat.S_IFMT(mode) not in (0, stat.S_IFREG):
            raise _bad_archive("'{}' is not a regular file".format(info.filename))
        total += info.file_size
        if total > MAX_UNPACKED_BYTES:
            raise _bad_archive("the unpacked content is too large")
        try:
            with zf.open(info) as f:
                content = f.read(info.file_size + 1)
        except (zipfile.BadZipFile, ValueError, OSError, zlib.error, NotImplementedError) as e:
            raise _bad_archive("'{}' could not be read ({})".format(info.filename, e))
        if len(content) != info.file_size:
            raise _bad_archive("'{}' has an inconsistent size".format(name))
        yield name, "file", content


def _gunzip_limited(data, limit):
    d = zlib.decompressobj(16 + zlib.MAX_WBITS)
    try:
        out = d.decompress(data, limit + 1)
    except zlib.error as e:
        raise _bad_archive("not a valid gzip file ({})".format(e))
    if len(out) > limit or d.unconsumed_tail:
        raise _bad_archive("the unpacked content is too large")
    if not d.eof or d.unused_data:
        raise _bad_archive("the gzip data is truncated or has trailing data")
    return out


def _tar_entries(data):
    raw = _gunzip_limited(data, MAX_UNPACKED_BYTES)
    try:
        tf = tarfile.open(fileobj=io.BytesIO(raw), mode="r:")
        members = tf.getmembers()
    except (tarfile.TarError, ValueError, OSError, EOFError) as e:
        raise _bad_archive("not a valid tar file ({})".format(e))
    if len(members) > MAX_ARCHIVE_ENTRIES:
        raise _bad_archive("too many entries")
    for member in members:
        name = member.name
        if member.issym() or member.islnk():
            raise _bad_archive("'{}' is a link".format(name))
        if member.isdir():
            yield name.rstrip("/"), "dir", None
        elif member.isreg():
            f = tf.extractfile(member)
            content = f.read() if f is not None else b""
            if len(content) != member.size:
                raise _bad_archive("'{}' has an inconsistent size".format(name))
            yield name, "file", content
        else:
            raise _bad_archive("'{}' is not a regular file".format(name))


def read_archive(data, platform):
    """Validates the archive and returns {relative path inside the mod folder: bytes}."""
    entries = _zip_entries(data) if platform == "windows" else _tar_entries(data)
    allowed = allowed_files(platform)
    files, seen = {}, set()
    for name, kind, content in entries:
        if not name or "\\" in name or ":" in name or name.startswith("/") or "\0" in name:
            raise _bad_archive("unsafe path {!r}".format(name))
        parts = name.split("/")
        if any(p in ("", ".", "..") for p in parts):
            raise _bad_archive("unsafe path {!r}".format(name))
        if name in seen:
            raise _bad_archive("duplicate entry '{}'".format(name))
        seen.add(name)
        if parts[0] != ltm.MOD_DIR_NAME:
            raise _bad_archive("unexpected top-level entry '{}'".format(name))
        rel = "/".join(parts[1:])
        if kind == "dir":
            if rel not in ALLOWED_DIRS:
                raise _bad_archive("unexpected directory '{}'".format(name))
            continue
        if rel not in allowed:
            raise _bad_archive("unknown file '{}'".format(name))
        files[rel] = content
    missing = sorted(allowed - set(files))
    if missing:
        raise _bad_archive("it is incomplete (missing {})".format(", ".join(missing)))
    return files


