def _snapshot(path):
    if not os.path.lexists(path):
        return None
    st = os.lstat(path)
    return ltm.read_bytes(path), stat.S_IMODE(st.st_mode)


def apply_update(game_dir, mod_dir, files, manifest, new_version):
    """Replaces the files atomically with rollback. Returns a list of notes for the player."""
    notes = []
    plan = []  # (absolute path, new bytes, is shell script, is loader)
    for rel in sorted(files):
        plan.append((ltm.game_path(mod_dir, rel), files[rel], rel.endswith(".sh"), False))

    loader_written_hash = None
    if manifest is not None:
        entry = ltm._find_entry(manifest["files"], ltm.LOADER_REL)
        shared = ltm._find_entry(manifest["preexisting"], ltm.LOADER_REL) is not None
        loader_path = ltm.game_path(game_dir, ltm.LOADER_REL)
        if entry is not None and shared:
            notes.append("version.dll in the game folder is shared with another mod (pre-existing) and was not "
                         "changed.")
        elif entry is not None:
            if os.path.lexists(loader_path) and not ltm.is_regular_file(loader_path):
                raise ModError("Refusing to replace '{}': it is not a regular file.".format(loader_path))
            if os.path.lexists(loader_path) and ltm.sha256_file(loader_path) != entry["sha256"]:
                notes.append("version.dll in the game folder was changed by something else and was not replaced. "
                             "Run Status for details.")
            else:
                plan.append((loader_path, files[ltm.LOADER_SOURCE_REL], False, True))
                loader_written_hash = ltm.sha256_bytes(files[ltm.LOADER_SOURCE_REL])

    for path, _data, _script, _loader in plan:
        if os.path.lexists(path) and not ltm.is_regular_file(path):
            raise ModError("Refusing to replace '{}': it is a link or not a regular file.".format(path),
                           hint="Nothing was changed.")
        parent = os.path.dirname(path)
        if os.path.lexists(parent) and (os.path.islink(parent) or not os.path.isdir(parent)):
            raise ModError("Refusing to write into '{}': it is a link or not a folder.".format(parent),
                           hint="Nothing was changed.")

    snapshots = {path: _snapshot(path) for path, _d, _s, _l in plan}
    changes = [p for p in plan if snapshots[p[0]] is None or snapshots[p[0]][0] != p[1]]

    manifest_path = os.path.join(mod_dir, ltm.MANIFEST_NAME)
    new_manifest_bytes = None
    old_manifest = None
    if manifest is not None:
        updated = json.loads(json.dumps(manifest))
        updated["mod_version"] = new_version
        if loader_written_hash is not None:
            ltm._find_entry(updated["files"], ltm.LOADER_REL)["sha256"] = loader_written_hash
        old_manifest = ltm.read_bytes(manifest_path)
        new_manifest_bytes = ltm.dump_manifest(updated)
        if new_manifest_bytes == old_manifest:
            new_manifest_bytes = None

    written, created_dirs = [], []
    manifest_written = False
    try:
        for path, data, is_script, _loader in changes:
            parent = os.path.dirname(path)
            if not os.path.isdir(parent):
                os.mkdir(parent)
                created_dirs.append(parent)
            snap = snapshots[path]
            if snap is not None:
                mode = snap[1] | (0o755 if is_script else 0)
            else:
                mode = 0o755 if is_script else None
            ltm.atomic_write(path, data, mode)
            written.append(path)
        if new_manifest_bytes is not None:
            ltm.atomic_write(manifest_path, new_manifest_bytes)
            manifest_written = True
    except Exception as e:
        failed = _rollback(written, snapshots, created_dirs, manifest_path if manifest_written else None,
                           old_manifest)
        if failed:
            raise ModError(
                "Update failed ({}) and these files could not be restored: {}.".format(e, ", ".join(failed)),
                hint="Download the archive for your platform from {} , extract it into the game folder "
                     "(replacing files), then run Install again. Your config.ini is unchanged.".format(
                         RELEASES_PAGE_URL))
        raise ModError("Update failed: {}. All files were restored to the previous version.".format(e),
                       hint="Make sure no program uses the mod's files and try again.")
    # Shell scripts must be executable even when their content did not change.
    if os.name == "posix":
        for path, _data, is_script, _loader in plan:
            if is_script and path not in written:
                try:
                    mode = stat.S_IMODE(os.stat(path).st_mode)
                    if mode & 0o111 != 0o111:
                        os.chmod(path, mode | 0o755)
                except OSError:
                    notes.append("Could not mark '{}' as executable; run: chmod +x '{}'".format(path, path))
    return notes, len(changes)


def _rollback(written, snapshots, created_dirs, manifest_path, old_manifest):
    failed = []
    for path in reversed(written):
        snap = snapshots[path]
        try:
            if snap is None:
                os.remove(path)
            else:
                ltm.atomic_write(path, snap[0], snap[1])
        except OSError:
            failed.append(path)
    if manifest_path is not None:
        try:
            ltm.atomic_write(manifest_path, old_manifest)
        except OSError:
            failed.append(manifest_path)
    for directory in reversed(created_dirs):
        try:
            os.rmdir(directory)
        except OSError:
            pass
    return failed


