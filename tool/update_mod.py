def select_latest_release(releases):
    """Returns (tag, release) of the highest vX.Y.Z release that is neither a draft nor a prerelease."""
    if not isinstance(releases, list):
        raise ModError("Unexpected response from GitHub (the release list is not a list).")
    best = None
    for release in releases:
        if not isinstance(release, dict):
            continue
        if release.get("draft") is not False or release.get("prerelease") is not False:
            continue
        tag = release.get("tag_name")
        m = STABLE_TAG_RE.match(tag) if isinstance(tag, str) else None
        if not m:
            continue
        key = tuple(int(x) for x in m.groups())
        if best is None or key > best[0]:
            best = (key, tag, release)
    if best is None:
        raise ModError("No stable release of the mod was found on GitHub.",
                       hint="See {}.".format(RELEASES_PAGE_URL))
    return best[1], best[2]


def select_asset(release, tag, platform):
    """Returns (url, size, sha256 hex or None) of this platform's archive in the release."""
    name = archive_name(tag, platform)
    assets = release.get("assets")
    matches = [a for a in assets if isinstance(a, dict) and a.get("name") == name] if isinstance(
        assets, list) else []
    if len(matches) != 1:
        raise ModError("Release {} has {} archive named {}.".format(tag, "no" if not matches else "more than one", name),
                       hint="See {}.".format(RELEASES_PAGE_URL))
    asset = matches[0]
    url = asset.get("browser_download_url")
    expected = DOWNLOAD_PREFIX + tag + "/" + name
    if url != expected:
        raise ModError("The download URL of {} is not the expected one ({!r}); refusing it.".format(name, url))
    size = asset.get("size")
    if not isinstance(size, int) or isinstance(size, bool) or size <= 0:
        raise ModError("The release metadata has no valid size for {}.".format(name))
    if size > MAX_ARCHIVE_BYTES:
        raise _too_large("release archive", MAX_ARCHIVE_BYTES)
    digest = asset.get("digest")
    sha256 = None
    if digest is not None:
        m = re.match(r"^sha256:([0-9a-fA-F]{64})$", digest) if isinstance(digest, str) else None
        if not m:
            raise ModError("The release metadata has an unsupported digest for {} ({!r}).".format(name, digest))
        sha256 = m.group(1).lower()
    return url, size, sha256


