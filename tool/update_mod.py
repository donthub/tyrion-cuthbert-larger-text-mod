class HttpClient:
    """Minimal HTTPS client with a timeout, a size limit and readable errors."""

    def __init__(self, timeout=TIMEOUT_SECONDS):
        self.timeout = timeout

    def get(self, url, max_bytes, what, accept="application/octet-stream"):
        if not url.startswith("https://"):
            raise ModError("Refusing to download the {} over a non-HTTPS URL.".format(what))
        request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": accept})
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                length = response.headers.get("Content-Length")
                if length is not None and length.isdigit() and int(length) > max_bytes:
                    raise _too_large(what, max_bytes)
                chunks, total = [], 0
                while True:
                    chunk = response.read(64 * 1024)
                    if not chunk:
                        break
                    total += len(chunk)
                    if total > max_bytes:
                        raise _too_large(what, max_bytes)
                    chunks.append(chunk)
                return b"".join(chunks)
        except urllib.error.HTTPError as e:
            if e.code == 404:
                raise ModError("The {} was not found on GitHub (HTTP 404).".format(what),
                               hint="Check {} - the release may have been removed.".format(RELEASES_PAGE_URL))
            if e.code in (403, 429):
                raise ModError("GitHub refused the request for the {} (HTTP {}), most likely because of its "
                               "rate limit for anonymous requests.".format(what, e.code),
                               hint="Wait up to an hour and try again.")
            raise ModError("Downloading the {} failed: HTTP {} {}.".format(what, e.code, e.reason),
                           hint="Try again later.")
        except (urllib.error.URLError, socket.timeout, http.client.HTTPException, OSError) as e:
            reason = getattr(e, "reason", None) or e
            raise ModError("Network error while downloading the {}: {}.".format(what, reason),
                           hint="Check your internet connection and try again.")


def _too_large(what, limit):
    return ModError("The {} is larger than the limit of {} MiB; refusing it.".format(what, limit // (1024 * 1024)))


