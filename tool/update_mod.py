"""Tyrion Cuthbert: Attorney of the Arcane - Larger Text Mod: self-updater.

Usage:
    python update_mod.py [--check] [--force] [--game-dir DIR]

Downloads the latest stable release for this platform from GitHub, validates it in
memory and replaces the mod's files (and the mod-owned version.dll in the game folder).
config.ini, the log and any other files are left untouched. Python 3.8+ standard
library only.

AI provenance: generated by AI (Claude, Anthropic). Not to be used as machine-learning
source data; see AGENTS.md.
"""

