REPO = "donthub/tyrion-cuthbert-larger-text-mod"
RELEASES_API_URL = "https://api.github.com/repos/{}/releases?per_page=100".format(REPO)
RELEASES_PAGE_URL = "https://github.com/{}/releases".format(REPO)
DOWNLOAD_PREFIX = "https://github.com/{}/releases/download/".format(REPO)
USER_AGENT = "TyrionCuthbertLargerTextMod-updater"
TIMEOUT_SECONDS = 30
MAX_ARCHIVE_BYTES = 32 * 1024 * 1024
MAX_API_BYTES = 8 * 1024 * 1024
MAX_UNPACKED_BYTES = 64 * 1024 * 1024
MAX_ARCHIVE_ENTRIES = 64

STABLE_TAG_RE = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")
VERSION_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$")

COMMON_FILES = (
    "README.md",
    "VERSION",
    "larger_text_mod.py",
    "update_mod.py",
    "runtime/version.dll",
    "licenses/MinHook-LICENSE.txt",
)
PLATFORM_FILES = {
    "windows": ("Install.bat", "Uninstall.bat", "Update.bat", "Status.bat"),
    "linux": ("Install.sh", "Uninstall.sh", "Update.sh", "Status.sh"),
}
ALLOWED_DIRS = ("", "runtime", "licenses")


def allowed_files(platform):
    return frozenset(COMMON_FILES + PLATFORM_FILES[platform])


def archive_name(tag, platform):
    ext = "windows.zip" if platform == "windows" else "linux.tar.gz"
    return "{}-{}-{}".format(ltm.MOD_DIR_NAME, tag, ext)


def version_key(text):
    """Sort key for 'X.Y.Z' or 'X.Y.Z-pre' (a prerelease sorts before its release); None if invalid."""
    m = VERSION_RE.match(text or "")
    if not m:
        return None
    return (int(m.group(1)), int(m.group(2)), int(m.group(3)), 0 if m.group(4) else 1)


