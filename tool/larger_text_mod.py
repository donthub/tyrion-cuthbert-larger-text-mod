_NUMBER_RE = re.compile(r"^[+-]?(\d+([.,]\d*)?|[.,]\d+)([eE][+-]?\d+)?$")
_BOOL_VALUES = {"true": True, "yes": True, "on": True, "1": True,
                "false": False, "no": False, "off": False, "0": False}


def parse_number(text):
    """Parses a finite decimal number (a decimal comma is accepted). Returns None if invalid."""
    if text is None:
        return None
    text = text.strip()
    if not _NUMBER_RE.match(text):
        return None
    try:
        value = float(text.replace(",", "."))
    except ValueError:
        return None
    return value if math.isfinite(value) else None


def parse_bool(text):
    return _BOOL_VALUES.get(text.strip().lower())


def format_number(value):
    return repr(float(value))


def validate_settings(scale_text, opacity_text):
    """Validates the command-line scale/opacity. Returns (scale or None, opacity or None)."""
    scale = opacity = None
    if scale_text is not None:
        scale = parse_number(scale_text)
        if scale is None or not SCALE_MIN <= scale <= SCALE_MAX:
            raise ModError(
                "Invalid scale '{}': it must be a number from 1.1 to 2.0.".format(scale_text),
                hint="Example: Install 1.3 (use a dot as the decimal separator).",
            )
    if opacity_text is not None:
        opacity = parse_number(opacity_text)
        if opacity is None or not OPACITY_MIN <= opacity <= OPACITY_MAX:
            raise ModError(
                "Invalid opacity '{}': it must be a number from 0.0 to 1.0.".format(opacity_text),
                hint="Example: Install 1.5 0.8 (use a dot as the decimal separator).",
            )
    return scale, opacity


def _strip_inline_comment(value):
    """Removes an inline comment: ';' or '#' at the start or after whitespace (as the runtime does)."""
    for i, ch in enumerate(value):
        if ch in ";#" and (i == 0 or value[i - 1].isspace()):
            return value[:i]
    return value


def default_settings():
    return {
        "enabled": True,
        "scale": SCALE_DEFAULT,
        "opacity": OPACITY_DEFAULT,
        "features": {key: True for key in FEATURE_KEYS},
    }


def parse_config(text):
    """Parses config.ini text the same way the runtime does. Returns (settings, warnings)."""
    settings = default_settings()
    warnings = []
    seen = set()
    section = ""
    if text.startswith("﻿"):
        text = text[1:]
    for line_no, raw in enumerate(text.split("\n"), 1):
        line = raw.strip()
        if not line or line[0] in ";#":
            continue
        if line[0] == "[":
            if not line.endswith("]"):
                warnings.append("line {}: malformed section header ignored".format(line_no))
                section = ""
                continue
            section = line[1:-1].strip().lower()
            continue
        if "=" not in line:
            warnings.append("line {}: expected 'key = value', ignored".format(line_no))
            continue
        key, value = line.split("=", 1)
        key = key.strip().lower()
        value = _strip_inline_comment(value).strip()
        ident = section + "." + key
        if ident in seen:
            warnings.append("'{}' appears more than once; the last value is used".format(key))
        seen.add(ident)
        if section == "general" and key == "enabled":
            b = parse_bool(value)
            if b is None:
                warnings.append("enabled: '{}' is not true/false; using default (true)".format(value))
            else:
                settings["enabled"] = b
        elif section == "general" and key in ("scale", "opacity"):
            lo, hi, default = ((SCALE_MIN, SCALE_MAX, SCALE_DEFAULT) if key == "scale"
                               else (OPACITY_MIN, OPACITY_MAX, OPACITY_DEFAULT))
            number = parse_number(value)
            if number is None:
                warnings.append("{}: '{}' is not a number; using default ({})".format(key, value, default))
                settings[key] = default
            elif not lo <= number <= hi:
                warnings.append("{}: {} is outside {}-{}; using default ({})".format(key, value, lo, hi, default))
                settings[key] = default
            else:
                settings[key] = number
        elif section == "features" and key in FEATURE_KEYS:
            b = parse_bool(value)
            if b is None:
                warnings.append("{}: '{}' is not true/false; using default (true)".format(key, value))
            else:
                settings["features"][key] = b
        # Unknown sections and keys are kept in the file and ignored here.
    for key, default in (("scale", SCALE_DEFAULT), ("opacity", OPACITY_DEFAULT)):
        if "general." + key not in seen:
            warnings.append("{} is missing; using default ({})".format(key, default))
    return settings, warnings


