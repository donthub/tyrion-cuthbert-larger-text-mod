_UNITY_VERSION_RE = re.compile(rb"(\d{4})\.(\d+)\.(\d+)[abfp]\d+")


def read_unity_version(data_dir):
    """Returns the Unity version string found in the data file header, or None."""
    for name in ("data.unity3d", "globalgamemanagers"):
        path = os.path.join(data_dir, name)
        if not os.path.isfile(path):
            continue
        try:
            with open(path, "rb") as f:
                head = f.read(4096)
        except OSError:
            continue
        m = _UNITY_VERSION_RE.search(head)
        if m:
            return m.group(0).decode("ascii")
    return None


def pe_imported_dlls(path):
    """Returns the DLL names in a PE file's import table. Raises ValueError for invalid files."""
    with open(path, "rb") as f:
        def read_at(offset, size):
            f.seek(offset)
            data = f.read(size)
            if len(data) != size:
                raise ValueError("truncated PE file")
            return data

        dos = read_at(0, 64)
        if dos[:2] != b"MZ":
            raise ValueError("not a PE file (no MZ header)")
        pe_offset = struct.unpack_from("<I", dos, 0x3C)[0]
        if read_at(pe_offset, 4) != b"PE\0\0":
            raise ValueError("not a PE file (no PE signature)")
        _machine, num_sections, _ts, _sym, _nsym, opt_size, _chars = struct.unpack(
            "<HHIIIHH", read_at(pe_offset + 4, 20))
        opt = read_at(pe_offset + 24, opt_size)
        if len(opt) < 2:
            raise ValueError("missing optional header")
        magic = struct.unpack_from("<H", opt, 0)[0]
        if magic == 0x20B:
            count_offset, dirs_offset = 108, 112
        elif magic == 0x10B:
            count_offset, dirs_offset = 92, 96
        else:
            raise ValueError("unknown optional header magic 0x{:x}".format(magic))
        if len(opt) < dirs_offset + 16:
            return []
        if struct.unpack_from("<I", opt, count_offset)[0] < 2:
            return []
        import_rva, _import_size = struct.unpack_from("<II", opt, dirs_offset + 8)
        if import_rva == 0:
            return []
        table = read_at(pe_offset + 24 + opt_size, 40 * num_sections)
        sections = []
        for i in range(num_sections):
            _name, vsize, vaddr, raw_size, raw_ptr = struct.unpack_from("<8sIIII", table, 40 * i)
            sections.append((vaddr, max(vsize, raw_size), raw_size, raw_ptr))

        def rva_to_offset(rva):
            for vaddr, span, raw_size, raw_ptr in sections:
                if vaddr <= rva < vaddr + span:
                    delta = rva - vaddr
                    if delta >= raw_size:
                        raise ValueError("RVA 0x{:x} has no file data".format(rva))
                    return raw_ptr + delta
            raise ValueError("RVA 0x{:x} is outside all sections".format(rva))

        names = []
        offset = rva_to_offset(import_rva)
        for i in range(4096):
            descriptor = read_at(offset + 20 * i, 20)
            if descriptor == b"\0" * 20:
                break
            name_rva = struct.unpack_from("<I", descriptor, 12)[0]
            f.seek(rva_to_offset(name_rva))
            names.append(f.read(256).split(b"\0", 1)[0].decode("ascii", "replace"))
        return names


def check_engine(game_dir):
    """Checks Unity 6000.x, IL2CPP and the VERSION.dll import. Returns the Unity version."""
    data_dir = os.path.join(game_dir, GAME_DATA_DIR)
    hint_verify = ("Use Steam's 'Verify integrity of game files'. If the game was updated to a new engine, "
                   "check for a mod update (Update).")
    version = read_unity_version(data_dir)
    if version is None:
        raise ModError("Could not determine the game's Unity version ({}/data.unity3d not found or "
                       "unreadable).".format(GAME_DATA_DIR), hint=hint_verify)
    if version.split(".", 1)[0] != "6000":
        raise ModError("Unsupported Unity version {}: this mod supports Unity 6000.x (Unity 6) only.".format(version),
                       hint=hint_verify)
    il2cpp_files = ("GameAssembly.dll",
                    GAME_DATA_DIR + "/il2cpp_data/Metadata/global-metadata.dat")
    missing = [rel for rel in il2cpp_files if not os.path.isfile(game_path(game_dir, rel))]
    if missing:
        raise ModError("Unsupported scripting backend: this mod needs IL2CPP, but {} was not found.".format(
            missing[0]), hint=hint_verify)
    player = os.path.join(game_dir, "UnityPlayer.dll")
    if not os.path.isfile(player):
        raise ModError("UnityPlayer.dll was not found in the game folder.", hint=hint_verify)
    try:
        imports = pe_imported_dlls(player)
    except (OSError, ValueError, struct.error) as e:
        raise ModError("Could not read UnityPlayer.dll ({}).".format(e), hint=hint_verify)
    if "version.dll" not in (name.lower() for name in imports):
        raise ModError("UnityPlayer.dll does not import VERSION.dll, so the mod's loader would not be loaded "
                       "by this game build.", hint=hint_verify)
    return version


