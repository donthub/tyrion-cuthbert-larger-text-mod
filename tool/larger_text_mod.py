def plan_loader(game_dir, manifest, new_hash):
    """Decides what to do with <game>/version.dll.

    Returns (action, previous_bytes, preexisting_hash):
      'add'         - file missing, copy ours
      'replace'     - our older loader (hash recorded in the manifest), replace it
      'keep'        - ours and already current
      'preexisting' - identical file that this mod did not add; reuse, never remove
    """
    path = game_path(game_dir, LOADER_REL)
    files = manifest.get("files") if manifest else None
    pre = manifest.get("preexisting") if manifest else None
    entry = _find_entry(files, LOADER_REL)
    pre_entry = _find_entry(pre, LOADER_REL)
    if not os.path.lexists(path):
        return "add", None, None
    if not is_regular_file(path):
        raise ModError("'{}' exists but is not a regular file; refusing to replace it.".format(path),
                       hint="Remove it yourself if it is not needed by another mod, then run Install again.")
    current = sha256_file(path)
    if current == new_hash:
        if pre_entry is not None or entry is None:
            return "preexisting", None, current
        return "keep", None, None
    if entry is not None and pre_entry is None and current == entry.get("sha256"):
        return "replace", read_bytes(path), None
    raise ModError(
        "The game folder already contains a different version.dll that does not belong to this mod "
        "(probably another mod or loader). It was not changed.",
        hint="Uninstall the other mod (or move its version.dll away) and run Install again. This mod cannot "
             "share version.dll with a different loader.",
    )


def _summary_lines(settings, warnings, game_dir, mod_dir):
    lines = [
        "  Scale:   {}".format(format_number(settings["scale"])),
        "  Opacity: {}".format(format_number(settings["opacity"])),
        "  Mod enabled (master switch): {}".format("yes" if settings["enabled"] else "NO - the mod changes nothing"),
    ]
    on = [k for k in FEATURE_KEYS if settings["features"][k]]
    off = [k for k in FEATURE_KEYS if not settings["features"][k]]
    lines.append("  Features enabled:  {}".format(", ".join(on) if on else "none"))
    if off:
        lines.append("  Features disabled: {}".format(", ".join(off)))
    for w in warnings:
        lines.append("  Config warning: {}".format(w))
    return lines


def proton_note_lines():
    return [
        "One-time Steam setup for Linux / Steam Deck (Proton):",
        "  In Steam, right-click the game > Properties > General > Launch Options and enter:",
        "    " + PROTON_LAUNCH_OPTION,
        "  Without it Proton ignores the mod's version.dll. It is needed only once and stays valid",
        "  after mod updates (you can leave it set even after uninstalling).",
    ]


def cmd_install(args, platform):
    scale, opacity = validate_settings(args.scale, args.opacity)
    ensure_game_not_running(platform)
    game_dir, mod_dir = resolve_dirs(args.game_dir)
    check_game_folder(game_dir, mod_dir)
    check_original_mod(game_dir, mod_dir)
    unity_version = check_engine(game_dir)
    manifest = load_manifest(mod_dir)

    source = game_path(mod_dir, LOADER_SOURCE_REL)
    if not is_regular_file(source):
        raise ModError("The mod's runtime file '{}' is missing.".format(source),
                       hint="Download the release archive again and extract it into the game folder.")
    loader_bytes = read_bytes(source)
    loader_hash = sha256_bytes(loader_bytes)
    action, old_loader, pre_hash = plan_loader(game_dir, manifest, loader_hash)

    config_path = game_path(game_dir, CONFIG_REL)
    old_config = None
    if os.path.lexists(config_path):
        if not is_regular_file(config_path):
            raise ModError("'{}' is not a regular file.".format(config_path))
        old_config = read_bytes(config_path)
        try:
            old_text = old_config.decode("utf-8")
        except UnicodeDecodeError:
            raise ModError("'{}' is not valid UTF-8 text.".format(config_path),
                           hint="Fix or delete config.ini, then run Install again.")
    else:
        old_text = None
    new_config = update_config_text(old_text, scale, opacity).encode("utf-8")
    settings, warnings = parse_config(new_config.decode("utf-8"))

    manifest_path = os.path.join(mod_dir, MANIFEST_NAME)
    old_manifest = read_bytes(manifest_path) if manifest is not None else None

    preexisting = [dict(e) for e in (manifest or {}).get("preexisting", []) if e.get("path") != LOADER_REL]
    if action == "preexisting":
        preexisting.append({"path": LOADER_REL, "sha256": pre_hash})
    extra_files = [dict(e) for e in (manifest or {}).get("files", [])
                   if e.get("path") not in (LOADER_REL, CONFIG_REL)]
    new_manifest = {
        "format": MANIFEST_FORMAT,
        "mod_version": read_mod_version(mod_dir),
        "installed_at": (manifest or {}).get("installed_at") or utc_now(),
        "files": [
            {"path": LOADER_REL, "sha256": loader_hash, "kind": "loader"},
            {"path": CONFIG_REL, "sha256": sha256_bytes(new_config), "kind": "config"},
        ] + extra_files,
        "generated": list(GENERATED_RELS),
        "preexisting": preexisting,
        "created_dirs": list((manifest or {}).get("created_dirs", [])),
    }

    loader_path = game_path(game_dir, LOADER_REL)
    print("Installing the Larger Text Mod into '{}'...".format(game_dir))
    steps = []  # what was done, for rollback
    try:
        # The manifest goes first, listing the intended files, so an interrupted install can be uninstalled.
        atomic_write(manifest_path, dump_manifest(new_manifest))
        steps.append("manifest")
        if old_config != new_config:
            atomic_write(config_path, new_config)
            steps.append("config")
        if action in ("add", "replace"):
            atomic_write(loader_path, loader_bytes)
            steps.append("loader")
        # Final hashes, read back from disk.
        for entry in new_manifest["files"][:2]:
            actual = sha256_file(game_path(game_dir, entry["path"]))
            if actual != entry["sha256"]:
                raise OSError("'{}' does not have the expected content after writing".format(entry["path"]))
        atomic_write(manifest_path, dump_manifest(new_manifest))
    except Exception as e:
        failed = _rollback_install(steps, action, old_loader, old_config, old_manifest,
                                   loader_path, config_path, manifest_path)
        if failed:
            raise ModError("Install failed ({}) and these files could not be restored: {}.".format(
                e, ", ".join(failed)),
                hint="Run Uninstall, then Install again. Make sure no other program uses these files.")
        raise ModError("Install failed: {}. All changes from this run were undone.".format(e),
                       hint="Make sure the game folder is writable and no program uses its files, then try again.")

    loader_state = {
        "add": "added",
        "replace": "updated",
        "keep": "already up to date",
        "preexisting": "already present (shared, recorded as pre-existing; Uninstall keeps it)",
    }[action]
    print("")
    print("Install complete (mod version {}, Unity {} detected).".format(new_manifest["mod_version"], unity_version))
    for line in _summary_lines(settings, warnings, game_dir, mod_dir):
        print(line)
    print("  Loader: {} ({})".format(loader_path, loader_state))
    print("  Config: {}".format(config_path))
    print("          Edit it to change settings; changes apply at the next game start.")
    print("  Log:    {}".format(os.path.join(mod_dir, LOG_NAME)))
    print("          Written at each game start; Status shows features that were skipped.")
    if platform == "linux":
        print("")
        for line in proton_note_lines():
            print(line)
    print("")
    print("Start the game to use the mod.")
    return 0


def _rollback_install(steps, action, old_loader, old_config, old_manifest, loader_path, config_path, manifest_path):
    failed = []

    def restore(path, old):
        try:
            if old is None:
                if os.path.lexists(path):
                    os.remove(path)
            else:
                atomic_write(path, old)
        except OSError:
            failed.append(path)

    if "loader" in steps:
        restore(loader_path, old_loader if action == "replace" else None)
    if "config" in steps:
        restore(config_path, old_config)
    if "manifest" in steps:
        restore(manifest_path, old_manifest)
    return failed


