def _windows_game_running():
    try:
        result = subprocess.run(
            ["tasklist", "/FI", "IMAGENAME eq " + GAME_EXE, "/FO", "CSV", "/NH"],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60,
        )
    except (OSError, subprocess.SubprocessError) as e:
        raise ModError("Could not check whether the game is running ({}).".format(e),
                       hint="Make sure the game is closed and try again.")
    output = result.stdout.decode("utf-8", "replace").lower()
    return '"{}"'.format(GAME_EXE.lower()) in output


def _linux_game_running(proc_root="/proc"):
    target = GAME_EXE.lower()
    own_pid = str(os.getpid())
    try:
        entries = os.listdir(proc_root)
    except OSError as e:
        raise ModError("Could not check whether the game is running ({}).".format(e),
                       hint="Make sure the game is closed and try again.")
    for entry in entries:
        if not entry.isdigit() or entry == own_pid:
            continue
        base = os.path.join(proc_root, entry)
        try:
            with open(os.path.join(base, "comm"), "rb") as f:
                comm = f.read().decode("utf-8", "replace").strip().lower()
            if comm == target:
                return True
            with open(os.path.join(base, "cmdline"), "rb") as f:
                cmdline = f.read()
        except OSError:
            continue  # process ended or not readable
        for arg in cmdline.split(b"\0"):
            name = arg.decode("utf-8", "replace").replace("\\", "/").rsplit("/", 1)[-1].strip().lower()
            if name == target:
                return True
    return False


def is_game_running(platform):
    if platform == "windows":
        return _windows_game_running()
    return _linux_game_running()


def ensure_game_not_running(platform):
    if is_game_running(platform):
        raise ModError("The game ({}) is running.".format(GAME_EXE),
                       hint="Close the game completely, then run this again.")


