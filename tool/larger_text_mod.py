def is_regular_file(path):
    """True for an existing regular file that is not a symbolic link."""
    try:
        st = os.lstat(path)
    except OSError:
        return False
    return stat.S_ISREG(st.st_mode)


def _fsync_dir(directory):
    if os.name != "posix":
        return
    try:
        fd = os.open(directory, os.O_RDONLY)
    except OSError:
        return
    try:
        os.fsync(fd)
    except OSError:
        pass
    finally:
        os.close(fd)


def atomic_write(path, data, mode=None):
    """Writes data to a temporary file next to path, fsyncs it, then renames it over path."""
    directory = os.path.dirname(os.path.abspath(path))
    tmp = os.path.join(directory, ".{}.{}.tmp".format(os.path.basename(path), os.getpid()))
    try:
        with open(tmp, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        if mode is not None:
            os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.remove(tmp)
        except OSError:
            pass
        raise
    _fsync_dir(directory)


