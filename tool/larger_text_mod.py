def check_rel_path(rel):
    """Manifest paths must stay inside the files this mod may own."""
    if not isinstance(rel, str) or not rel or "\\" in rel or ":" in rel or rel.startswith("/"):
        return False
    parts = rel.split("/")
    if any(p in ("", ".", "..") for p in parts):
        return False
    return rel == LOADER_REL or (parts[0] == MOD_DIR_NAME and len(parts) > 1)


def _manifest_error(path, detail):
    return ModError(
        "The manifest '{}' is invalid ({}).".format(path, detail),
        hint="If you did not edit it: delete manifest.json, delete version.dll from the game folder if it "
             "was added by this mod, and run Install again.",
    )


def load_manifest(mod_dir):
    """Returns the validated manifest dict, or None if there is none."""
    path = os.path.join(mod_dir, MANIFEST_NAME)
    if not os.path.lexists(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as e:
        raise _manifest_error(path, e)
    if not isinstance(data, dict) or data.get("format") != MANIFEST_FORMAT:
        raise _manifest_error(path, "unknown format")
    files = data.get("files")
    generated = data.get("generated", [])
    preexisting = data.get("preexisting", [])
    created_dirs = data.get("created_dirs", [])
    if not all(isinstance(x, list) for x in (files, generated, preexisting, created_dirs)):
        raise _manifest_error(path, "missing lists")
    for entry in files + preexisting:
        if not isinstance(entry, dict) or not check_rel_path(entry.get("path")) or not isinstance(
                entry.get("sha256"), str):
            raise _manifest_error(path, "bad file entry {!r}".format(entry))
    for entry in files:
        if entry.get("kind") not in ("loader", "config", "other"):
            raise _manifest_error(path, "bad file kind {!r}".format(entry.get("kind")))
    for rel in generated + created_dirs:
        if not check_rel_path(rel):
            raise _manifest_error(path, "unsafe path {!r}".format(rel))
    data["generated"] = generated
    data["preexisting"] = preexisting
    data["created_dirs"] = created_dirs
    return data


def dump_manifest(manifest):
    return (json.dumps(manifest, indent=2) + "\n").encode("utf-8")


def _find_entry(entries, rel):
    for entry in entries or ():
        if entry.get("path") == rel:
            return entry
    return None


