_KEY_LINE_RE = re.compile(r"^(\s*)([^=\s]+)(\s*=[ \t]*)(.*?)$")


def update_config_text(text, scale=None, opacity=None):
    """Returns config text with scale/opacity in [general] set (only those given).

    Everything else - comments, unknown keys, feature switches, line endings - is kept.
    text=None creates the documented default config.
    """
    if text is None:
        return default_config_text(
            SCALE_DEFAULT if scale is None else scale,
            OPACITY_DEFAULT if opacity is None else opacity,
        )
    updates = {}
    if scale is not None:
        updates["scale"] = format_number(scale)
    if opacity is not None:
        updates["opacity"] = format_number(opacity)
    if not updates:
        return text
    bom = "﻿" if text.startswith("﻿") else ""
    body = text[len(bom):]
    newline = "\r\n" if "\r\n" in body else "\n"
    lines = body.splitlines(True)
    section = None
    found = set()
    general_end = None  # index after which missing keys are inserted
    for i, raw in enumerate(lines):
        content = raw.rstrip("\r\n")
        ending = raw[len(content):]
        code = content.strip()
        if code.startswith("["):
            section = code[1:-1].strip().lower() if code.endswith("]") else ""
            if section == "general":
                general_end = i
            continue
        if section != "general" or not code or code[0] in ";#":
            continue
        general_end = i
        m = _KEY_LINE_RE.match(content)
        if not m or "=" not in content:
            continue
        key = m.group(2).lower()
        if key not in updates:
            continue
        rest = m.group(4)
        value = _strip_inline_comment(rest)
        comment = rest[len(value):]
        trailing_ws = value[len(value.rstrip()):]
        lines[i] = m.group(1) + m.group(2) + m.group(3) + updates[key] + (trailing_ws + comment if comment else "") + ending
        found.add(key)
    missing = [k for k in ("scale", "opacity") if k in updates and k not in found]
    if missing:
        new_lines = ["{} = {}{}".format(k, updates[k], newline) for k in missing]
        if general_end is None:
            if lines and not lines[-1].endswith("\n"):
                lines[-1] += newline
            lines.extend([newline, "[general]" + newline] + new_lines)
        else:
            if not lines[general_end].endswith("\n"):
                lines[general_end] += newline
            lines[general_end + 1:general_end + 1] = new_lines
    return bom + "".join(lines)


