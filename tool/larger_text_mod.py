def cmd_uninstall(args, platform):
    ensure_game_not_running(platform)
    game_dir, mod_dir = resolve_dirs(args.game_dir)
    check_game_folder(game_dir, mod_dir)
    manifest = load_manifest(mod_dir)
    if manifest is None:
        print("No installation found (no {} in the mod folder). Nothing to do.".format(MANIFEST_NAME))
        return 0

    pre_paths = {e["path"] for e in manifest["preexisting"]}
    remove, kept_changed, kept_shared = [], [], []
    for entry in manifest["files"]:
        rel = entry["path"]
        path = game_path(game_dir, rel)
        if rel in pre_paths:
            kept_shared.append(rel)
            continue
        if not os.path.lexists(path):
            continue
        if not is_regular_file(path):
            kept_changed.append((rel, "not a regular file"))
        elif entry["kind"] == "config" or sha256_file(path) == entry["sha256"]:
            remove.append(rel)
        else:
            kept_changed.append((rel, "changed by something else since install"))
    for rel in manifest["generated"]:
        if rel not in pre_paths and rel not in remove and is_regular_file(game_path(game_dir, rel)):
            remove.append(rel)

    # Move files aside first so that a failure can be undone completely.
    staged = []
    try:
        for rel in remove:
            path = game_path(game_dir, rel)
            backup = path + ".ltm-uninstall"
            os.replace(path, backup)
            staged.append((path, backup))
    except OSError as e:
        for path, backup in reversed(staged):
            try:
                os.replace(backup, path)
            except OSError:
                pass
        raise ModError("Could not remove '{}' ({}). Nothing was removed.".format(rel, e.strerror or e),
                       hint="Make sure the game and other programs using these files are closed, then try again.")
    leftovers = []
    for path, backup in staged:
        try:
            os.remove(backup)
        except OSError:
            leftovers.append(backup)
    for rel in sorted(manifest["created_dirs"], key=lambda r: r.count("/"), reverse=True):
        try:
            os.rmdir(game_path(game_dir, rel))
        except OSError:
            pass
    os.remove(os.path.join(mod_dir, MANIFEST_NAME))

    print("Uninstall complete.")
    for rel in remove:
        print("  Removed: {}".format(rel))
    for rel in kept_shared:
        print("  Kept (existed before install, shared with another mod): {}".format(rel))
    for rel, reason in kept_changed:
        print("  WARNING: Left in place ({}): {}".format(reason, rel))
    for path in leftovers:
        print("  WARNING: Could not delete the temporary file '{}'; delete it yourself.".format(path))
    print("The game folder no longer loads the mod. You can delete the {} folder now.".format(MOD_DIR_NAME))
    if platform == "linux":
        print("The Steam launch option {} can stay; it is harmless without the mod.".format(PROTON_LAUNCH_OPTION))
    return 0


