class UsageError(Exception):
    pass


class _Parser(argparse.ArgumentParser):
    def error(self, message):
        raise UsageError(message)


def build_parser():
    parser = _Parser(prog="larger_text_mod.py",
                     description="Install, uninstall or check the Tyrion Cuthbert Larger Text Mod.")
    sub = parser.add_subparsers(dest="command", metavar="{install,uninstall,status}")
    sub.required = True
    p = sub.add_parser("install", help="install the mod or change its settings")
    p.add_argument("--scale", help="text size multiplier, 1.1 to 2.0 (default 1.5; kept on re-install)")
    p.add_argument("--opacity", help="dialogue panel background opacity, 0.0 to 1.0 (default 0.99; kept on re-install)")
    p.add_argument("--game-dir", help="game folder (default: parent of the mod folder)")
    p = sub.add_parser("uninstall", help="remove everything Install added")
    p.add_argument("--game-dir", help="game folder (default: parent of the mod folder)")
    p = sub.add_parser("status", help="show the installation status (never writes)")
    p.add_argument("--game-dir", help="game folder (default: parent of the mod folder)")
    return parser


def print_error(message, hint=None):
    print("ERROR: " + message, file=sys.stderr)
    if hint:
        print("Hint: " + hint, file=sys.stderr)


def setup_stdio():
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(errors="replace")
        except (AttributeError, ValueError):
            pass


def main(argv=None):
    setup_stdio()
    parser = build_parser()
    try:
        args = parser.parse_args(argv)
    except UsageError as e:
        print_error(str(e), hint="Run with --help for usage.")
        return 2
    except SystemExit as e:  # --help
        return e.code if isinstance(e.code, int) else 0
    try:
        platform = check_platform()
        handler = {"install": cmd_install, "uninstall": cmd_uninstall, "status": cmd_status}[args.command]
        return handler(args, platform)
    except ModError as e:
        print_error(e.message, e.hint)
        return 1
    except KeyboardInterrupt:
        print_error("Interrupted.")
        return 130
    except Exception as e:  # never show a traceback to players
        print_error("Unexpected error: {}: {}".format(type(e).__name__, e),
                    hint="Please report this on the mod's GitHub page.")
        return 1


if __name__ == "__main__":
    sys.exit(main())
