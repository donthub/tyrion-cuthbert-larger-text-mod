_FEATURE_LINE_RE = re.compile(r"FEATURE\s+(\S+)\s+(applied|disabled|skipped|failed)(?::\s*(.*))?\s*$")


def read_feature_outcomes(log_path):
    """Returns [(feature, outcome, reason)] from the log of the last game start."""
    outcomes = []
    with open(log_path, "rb") as f:
        text = f.read().decode("utf-8", "replace")
    for line in text.splitlines():
        m = _FEATURE_LINE_RE.search(line)
        if m:
            outcomes.append((m.group(1), m.group(2), (m.group(3) or "").strip()))
    return outcomes


def cmd_status(args, platform):
    game_dir, mod_dir = resolve_dirs(args.game_dir)
    check_game_folder(game_dir, mod_dir)
    manifest = load_manifest(mod_dir)
    log_path = os.path.join(mod_dir, LOG_NAME)
    if manifest is None:
        print("Status: NOT INSTALLED")
        print("  Run Install to install the mod.")
    else:
        problems = []
        pre = {e["path"]: e for e in manifest["preexisting"]}
        for entry in manifest["files"]:
            rel = entry["path"]
            path = game_path(game_dir, rel)
            if not os.path.lexists(path):
                problems.append("missing: {}".format(rel))
            elif not is_regular_file(path):
                problems.append("not a regular file: {}".format(rel))
            elif entry["kind"] != "config" and rel not in pre and sha256_file(path) != entry["sha256"]:
                problems.append("changed: {}".format(rel))
        for rel, entry in pre.items():
            path = game_path(game_dir, rel)
            if not _find_entry(manifest["files"], rel) and not os.path.lexists(path):
                problems.append("missing: {}".format(rel))
        if problems:
            print("Status: INCOMPLETE (mod version {})".format(manifest.get("mod_version", "unknown")))
            for p in problems:
                print("  " + p)
            print("  Steam's file verification or a game update may have removed or replaced these files.")
            print("  Run Install again to restore the installation (your settings are kept).")
        else:
            print("Status: INSTALLED (mod version {})".format(manifest.get("mod_version", "unknown")))
            config_path = game_path(game_dir, CONFIG_REL)
            with open(config_path, "rb") as f:
                settings, warnings = parse_config(f.read().decode("utf-8", "replace"))
            print("  Scale:   {}".format(format_number(settings["scale"])))
            print("  Opacity: {}".format(format_number(settings["opacity"])))
            print("  Master switch (enabled): {}".format("on" if settings["enabled"] else "OFF"))
            for key in FEATURE_KEYS:
                print("  Feature {:<22} {}".format(key + ":", "on" if settings["features"][key] else "off"))
            for w in warnings:
                print("  Config warning: {}".format(w))
            print("  Config: {}".format(config_path))
    print("  Log:    {}".format(log_path))
    if is_regular_file(log_path):
        try:
            outcomes = read_feature_outcomes(log_path)
        except OSError as e:
            print("  The log could not be read ({}).".format(e))
            outcomes = None
        if outcomes is not None:
            bad = [o for o in outcomes if o[1] in ("skipped", "failed")]
            applied = sorted({o[0] for o in outcomes if o[1] == "applied"})
            print("  Last game start:")
            if applied:
                print("    applied: {}".format(", ".join(applied)))
            if bad:
                for feature, outcome, reason in bad:
                    print("    {} {}: {}".format(feature, outcome, reason or "(no reason given)"))
            else:
                print("    no features were skipped or failed.")
    else:
        print("  (no log yet - it is written when the game starts with the mod installed)")
    if manifest is not None and platform == "linux":
        print("  Linux / Steam Deck: the Steam launch option {} is required.".format(PROTON_LAUNCH_OPTION))
    return 0


